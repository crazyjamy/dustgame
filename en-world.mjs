// Stored journal and postcard text can contain multiple authored passages in a single node.
export function worldText(text, translate) {
  const postcard = text.match(/^(.+) 돌아오면 (.+) 곁에서 이 이야기를 들려줄게요\.$/su);
  if (postcard) return translate(postcard[1])+' When I get back, I’ll tell you this story beside the '+translate(postcard[2])+'.';
  const wish = text.match(/^“(.+)” 그 작은 마음을 알아주었어요\. 반짝이 (\d+)개를 나누었어요\.$/u);
  if (wish) return '“'+translate(wish[1])+'” You understood that little wish. Your friend shared '+wish[2]+' sparkles.';
  const scene = text.match(/^(.+) 장면이 남았어요\. (.+)$/su);
  if (scene) return 'A memory of “'+translate(scene[1])+'” remains. '+translate(scene[2]);
  const title = text.match(/^(.+)의 후일담 · (.+)$/u);
  if (title) return translate(title[1])+'’s epilogue · '+translate(title[2]);
  if (text.includes('\n') && text.split('\n').every(line => /^[^ ]+[은는] /.test(line))) {
    return text.split('\n').map(translate).join('\n');
  }
  return null;
}
